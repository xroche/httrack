#!/bin/bash
#
# Regenerate htsentities.h from the WHATWG named character references.

set -euo pipefail

src=entities.json
url=https://html.spec.whatwg.org/entities.json
dest=htsentities.h

# 64-bit FNV-1a of $1, printed as a C constant. Must match the hash in
# htsencoding.c. The offset basis is stored as its wrapped (signed) bit pattern;
# bash arithmetic is 64-bit two's complement, so the result is bit-exact.
fnv1a() {
    local s=$1 i c h=$((0xcbf29ce484222325))
    for ((i = 0; i < ${#s}; i++)); do
        printf -v c '%d' "'${s:i:1}"
        h=$(((h ^ (c & 0xff)) * 0x100000001b3))
    done
    printf '0x%016xULL' "$h"
}

if [ ! -f "$src" ]; then
    curl -fsS "$url" -o "$src"
fi

# Keep ';'-terminated single-codepoint names; the ~93 multi-codepoint refs can't
# fit decode_entity's single-codepoint return and are skipped (left verbatim).
pairs=$(jq -r '
    to_entries
    | map(select((.key | endswith(";")) and (.value.codepoints | length == 1)))
    | sort_by(.key)
    | .[] | "\(.key | ltrimstr("&") | rtrimstr(";"))\t\(.value.codepoints[0])"' "$src")

# Skipped multi-codepoint names, kept to prove none aliases an emitted hash.
skipped=$(jq -r '
    to_entries
    | map(select((.key | endswith(";")) and (.value.codepoints | length > 1)))
    | .[] | .key | ltrimstr("&") | rtrimstr(";")' "$src")

rows=""
emit_hashes=""
width=0
while IFS=$'\t' read -r name cp; do
    hash=$(fnv1a "$name")
    row="{$hash, $cp, ${#name}},"
    ((${#row} > width)) && width=${#row}
    rows+="$row"$'\t'"$name"$'\n'
    emit_hashes+="$hash"$'\n'
done <<<"$pairs"
# Fixed-width lowercase hex, so a byte sort is a numeric sort on the hash.
# Comments are padded to one column, as clang-format aligns them.
rows=$(printf '%s' "$rows" | LC_ALL=C sort |
    while IFS=$'\t' read -r row name; do
        printf '    %-*s /* %s */\n' "$width" "$row" "$name"
    done)

skip_hashes=""
while IFS= read -r name; do
    [ -n "$name" ] && skip_hashes+="$(fnv1a "$name")"$'\n'
done <<<"$skipped"

# The lookup keys on the hash alone, so it is correct only while every emitted
# name hashes uniquely; prove it here, no runtime name compare needed.
dups=$(printf '%s' "$emit_hashes" | sort | uniq -d || true)
if [ -n "$dups" ]; then
    echo "FATAL: two entity names share a hash (duplicate table key); change the hash:" >&2
    echo "$dups" >&2
    exit 1
fi
# A skipped name colliding with an emitted hash would mis-decode instead of
# staying verbatim; forbid that too.
aliased=$(comm -12 <(printf '%s' "$emit_hashes" | sort -u) <(printf '%s' "$skip_hashes" | sort -u) || true)
if [ -n "$aliased" ]; then
    echo "FATAL: a skipped multi-codepoint name aliases an emitted hash:" >&2
    echo "$aliased" >&2
    exit 1
fi

cat >"$dest" <<EOF
/* GENERATED by $0 from the WHATWG named character references
   (${url}). DO NOT EDIT.
   Rows are sorted by a 64-bit FNV-1a hash of the entity name; the generator
   aborts on any hash collision, so no runtime name compare is needed. */

#include <stddef.h>
#include <stdint.h>

static const struct {
  uint64_t hash;
  uint32_t cp;
  uint8_t len;
} entity_table[] = {
${rows}
};

/* Returns the code point of the entity whose name hashes to hash and is len
   bytes long, or -1. */
static int decode_entity(const uint64_t hash, const size_t len) {
  size_t lo = 0, hi = sizeof(entity_table) / sizeof(entity_table[0]);

  while (lo < hi) {
    const size_t mid = lo + (hi - lo) / 2;

    if (entity_table[mid].hash < hash) {
      lo = mid + 1;
    } else if (entity_table[mid].hash > hash) {
      hi = mid;
    } else {
      return entity_table[mid].len == len ? (int) entity_table[mid].cp : -1;
    }
  }
  return -1;
}
EOF

echo "wrote $dest ($(grep -c '^    {0x' "$dest") entities)" >&2
